class FakeTransport(Transport):
    """The one seam scripts/verify_trust_measurements.py's samplers read through.

    Substituting here rather than stubbing the parsers is what keeps the two
    scripts sharing one COSE reader and one JWT reader: these fixtures are the
    bytes those parsers are given, not values handed past them.

    No peer certificate is returned, so `sample_aws_enclave` reports that the
    Nitro document's certificate binding is unverifiable. The check does not
    read that field and does not claim the AWS read is authenticated; see the
    module docstring under WHAT THIS DOES NOT ESTABLISH in the script.
    """

    def __init__(self, table: dict[str, bytes]) -> None:
        self.table = table

    def fetch(
        self, url: str, *, verify_tls: bool = True, want_peer_certificate: bool = False
    ) -> Fetched:
        if url not in self.table:
            raise ValueError(f"nothing serving {url}")
        return Fetched(self.table[url])


def transport_from(live: dict[str, bytes] | None = None) -> FakeTransport:
    return FakeTransport(LIVE if live is None else live)


def run(spec_name: str, record: dict[str, Any], written: frozenset[str], **kwargs: Any):  # noqa: ANN201
    return check_plane(
        PLANES[spec_name],
        record,
        written,
        transport=kwargs.pop("transport", transport_from()),
        source=kwargs.pop("source", source_from()),
        list_package=kwargs.pop("list_package", lister_from()),
        **kwargs,
    )


def problems(results: list[RegionResult]) -> str:
    return " | ".join(problem for result in results for problem in result.problems)


def module(source: str, path: str = "src/trusted_router/byok_crypto.py") -> dict[str, str]:
    return {path: source}


