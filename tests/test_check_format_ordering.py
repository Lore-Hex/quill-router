"""The pull-request check that turns the BYOK envelope ordering constraint into CI.

THE LAW
-------
A control plane may run only a build whose set of WRITTEN BYOK envelope formats
is a subset of the formats accepted by EVERY enclave serving that cloud, in
every region, and the check must refuse whenever it cannot establish that subset
relation — not only when it can disprove it.

WHY THIS IS A PROOF AND NOT A TEST
----------------------------------
The thing under test is a refusal. Its value is entirely in the cases where it
says no, and a refusal that never fires is indistinguishable from no check at
all while looking exactly like a check in CI. So the assertions here are almost
all negative: fabricate the outage, fabricate the missing provenance, fabricate
the region nobody wrote down, and require a non-zero verdict for each. The happy
path is one test out of many, and it is the least interesting one.

The subset relation also has to be DERIVED on both sides, and that is asserted
too. A check that hardcodes "writes V2, needs V2" is correct until the day a V3
write lands, at which point it keeps passing while asserting a fact about a
format the build no longer writes.

BOTH SIDES OF THAT DERIVATION WERE DEFEATED, THE WRITE SIDE TWICE
------------------------------------------------------------------
Adversarial review broke both halves, and the tests it produced are kept here as
the ones that matter most:

* ACCEPTS came from parsing case labels out of the switch in `envelopeAAD`.
  Four compiling, gofmt-clean edits kept `case AlgorithmV2:` in cache.go while
  rejecting v2 at run time — an erroring case body, a kill switch ahead of the
  switch, a rejection in the caller, a renamed live dispatch with the old
  function left as dead code — and all four passed with exit 0. The check now
  reads a declaration the enclave repo GENERATES from a round trip through
  (*Cache).Resolve, and binds it to that commit's package by sha256.
  `test_a_case_label_is_not_acceptance` and
  `test_a_declaration_that_no_longer_matches_the_package_blocks` are that fix.
* WRITES came from calls spelled `EncryptedSecretEnvelope` in one hardcoded
  file. An alias, a subclass, dataclasses.replace, an assignment to
  `.algorithm`, and a write site in any other module were all invisible. The
  fix was a wider scan, and a SECOND review walked past that one too — an
  annotated alias, an alias imported from a sibling module, a subclass defined
  in a sibling module — because the answer was still syntax.
  `test_written_formats_sees_a_v3_written_through_an_indirection` carries every
  shape from both rounds.
* So the write side is no longer primarily syntax. `probe_write_entry_points()`
  CALLS this tree and reads `.algorithm` off the envelopes those calls produced,
  and the check uses the union of that and the scan. The tests for it are
  `test_the_probe_reports_the_format_a_real_call_produced`,
  `test_the_probe_refuses_when_its_recorder_is_blind`, and
  `test_an_entry_point_with_no_probe_is_a_refusal` — the last being the
  enumeration closure that keeps the probe's coverage checkable rather than
  claimed.

TWO PATHS, AND THE CONSTANT THAT ROUTES BETWEEN THEM
-----------------------------------------------------
The check runs on every pull request (.github/workflows/ci.yml), so it must be
silent on the pull requests that do not touch envelope formats — and the loud
path CANNOT pass for any cloud today. Read live on 2026-08-16: AWS and Azure
publish `"source_commit": "not-configured"`, and GCP's `f57b791` carries no
`accepted_formats.json` (that file is generated by quill-cloud-proxy#177, which
is not merged). `main()` therefore routes on one comparison: the derived written
set against `BASELINE_WRITTEN_FORMATS`.

That constant is hand-maintained, which is the defect class this repository
keeps being bitten by, so it is pinned rather than believed:
`test_the_baseline_matches_what_this_tree_writes` runs the real derivation
against the real tree and asserts equality. Without it the check is silent
whenever the constant is stale, which is the same as not running. The other two
directions are `test_an_unchanged_write_side_is_silent_and_reads_no_network`,
which drives the real `main()` with EVERY network seam replaced by a function
that raises, and `test_a_new_written_format_takes_the_loud_path_and_blocks`.

WHAT NO TEST HERE COVERS ABOUT THE ROUTING
-------------------------------------------
A change that alters the written set and updates BASELINE_WRITTEN_FORMATS in the
same commit is silent from the NEXT commit onwards. What makes that safe is that
the two edits are one diff, arriving together in front of a reviewer, and that
the loud path has already run on the commit that made them differ. Nothing here
enforces that a human read that diff.

SCOPE LIMIT, stated plainly
---------------------------
* Nothing here touches the network, so nothing here proves the live attestation
  endpoints answer, that the published records are reachable, or that
  raw.githubusercontent.com serves a file at an arbitrary commit. Those are
  the check's real failure modes in production and they are covered only by it
  failing closed on any exception, which IS asserted, on fabricated exceptions.
* No signature is verified here or by the code under test. The attestation
  fixtures below are unsigned, and the check would accept them in production
  too; it reads attestations through scripts/verify_trust_measurements.py's own
  samplers, which do not verify signatures either.
* `source_commit` is an assertion by whoever ran the enclave release, not a
  measurement. These tests prove the check refuses when it is absent. They
  cannot prove — and neither can the check — that a present one is the commit
  that built the running enclave.
* The accepted-formats declaration is proved here to be bound to the package
  source at the same commit, for every non-test .go file that commit's package
  contains. It is NOT proved to have been generated rather than hand-written;
  that is quill-cloud-proxy's CI running the generating test, and the property
  that the generator measures behaviour is proved there, in
  enclave-go/internal/byokcache/accepted_formats_test.go, not here. Nor does
  anything here or there show that the round trip the declaration records would
  still succeed under the enclave's own run-time configuration: a v2 refusal
  behind an environment variable produces a green CI and a V1,V2 declaration.
* The behavioural write probe is exercised here against the REAL modules, so
  these tests do depend on this tree importing and on a local AES key wrapper
  working. They do not prove that every write path is probed — that is the
  enumeration closure, which is itself only as complete as the return
  annotations in src/trusted_router.
* The subset check is over algorithm STRINGS. It does not prove the two
  implementations of a shared format agree byte for byte; that is
  tests/test_byok_aad_namespace_property.py's pinned hex vector, and the two
  proofs are independent.
* Region coverage: the check refuses when the record accepts a measurement this
  run never observed, and `test_an_accepted_measurement_no_region_served
  _blocks` fabricates exactly the shape the live Azure mirror had. What no test
  and no check can see is an enclave serving a cloud while appearing in neither
  the record's `regions` array nor its accepted set.
* Nothing here, and nothing in the code under test, stops a DEPLOY. The check
  is a CI job; deploy.yml and both hand-run cloud scripts do not call it.
"""

