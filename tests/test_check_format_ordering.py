def test_the_baseline_matches_what_this_tree_writes() -> None:
    """MANDATORY. Without this assertion the design in the script is unsound.

    `main()` is silent — no record fetched, no enclave contacted — exactly when
    the derived written set equals BASELINE_WRITTEN_FORMATS. That constant is
    hand-maintained, and a hand-maintained constant that has drifted from what
    the tree writes makes the check silent about a real format change: it would
    compare V3 against a stale {V2} and take the loud path for the wrong reason,
    or, worse, a baseline edited to match a V3 write nobody verified would make
    every later run silent about it.

    So the constant is not believed. The real derivation runs against the real
    tree here and the two must be equal, which means the commit that changes
    what this tree writes cannot also leave the baseline stale: one of the two
    assertions fails until both edits are present, and the loud path has run on
    the commit in between.
    """
    derived = derive_written_formats(read_write_surface()).formats

    assert derived == BASELINE_WRITTEN_FORMATS, (
        "BASELINE_WRITTEN_FORMATS in scripts/check_format_ordering.py no longer equals what "
        "this tree writes. If this change is deliberate, the loud path must have cleared for "
        "every cloud on this commit BEFORE the constant is updated to match."
    )


def drive_main(
    monkeypatch: pytest.MonkeyPatch,
    argv: list[str],
    *,
    records: dict[str, dict[str, Any]] | None = None,
) -> int:
    """Run the REAL main() over the fabricated world, with no network.

    Only the four I/O seams are replaced — record fetch, the transport the
    attestation samplers read through, enclave file read, enclave package
    listing. Everything else, including the write derivation against this
    working tree, is the production path.
    """
    table = records or {
        "/trust/aws-release.json": aws_record(source_commit=COMMIT_V1_ONLY),
        "/trust/gcp-release.json": gcp_record(),
    }
    monkeypatch.setattr(gate, "fetch_record", lambda plane, path: table[path])  # noqa: ARG005
    monkeypatch.setattr(gate, "NetworkTransport", transport_from)
    monkeypatch.setattr(gate, "fetch_enclave_file", source_from())
    monkeypatch.setattr(gate, "fetch_enclave_package_files", lister_from())
    return gate.main(argv)


def surface_writing_v3() -> dict[str, str]:
    """The real write surface plus one module that writes a third format.

    A new module with a new module-level constant is how a v3 migration
    actually starts, and it is what the syntactic scan reads. It is not the same
    thing as editing byok_crypto.py to write V3 through the real key path — that
    is the empirical demonstration this check was proved with, and it cannot be
    a committed test because a tree that writes V3 fails
    `test_the_baseline_matches_what_this_tree_writes` by construction.
    """
    surface = dict(read_write_surface())
    surface["src/trusted_router/byok_crypto_v3.py"] = (
        f'ALGORITHM_V3 = "{V3}"\n'
        "def seal():\n"
        "    return EncryptedSecretEnvelope(algorithm=ALGORITHM_V3)\n"
    )
    return surface


def test_an_unchanged_write_side_is_silent_and_reads_no_network(
    monkeypatch: pytest.MonkeyPatch, capsys: pytest.CaptureFixture[str]
) -> None:
    """The path every ordinary pull request takes, proved by breaking the network.

    The requirement is not "it happens to pass today". It is that a pull request
    which does not change the written format set cannot be reddened by anything
    outside this repository — and today that matters concretely, because the AWS
    and Azure records publish no `source_commit`, so the loud path CANNOT clear
    for them (see `test_missing_source_commit_blocks`). If the silent path
    touched the network at all, this check would be red on every pull request
    within a week of landing and deleted the week after.

    So every seam that could reach outside this process is replaced by a
    function that raises, including `gather` itself. Exit 0 with all of them
    armed is the proof that none of them was called.
    """

    def unreachable(*args: Any, **kwargs: Any) -> Any:
        raise AssertionError("the silent path must not perform any network I/O")

    for name in (
        "_fetch",
        "fetch_record",
        "fetch_enclave_file",
        "fetch_enclave_package_files",
        "NetworkTransport",
        "gather",
    ):
        monkeypatch.setattr(gate, name, unreachable)

    assert gate.main([]) == 0

    out = capsys.readouterr().out
    assert "no attestation endpoint was contacted" in out
    assert "BLOCKED" not in out


